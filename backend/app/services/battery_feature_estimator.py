def estimate_battery_costs(
    capacity_kwh: float,
    chemistry: str,
    soh_pct: float,
    vehicle_model: str | None = None,
    pathway: str = "SECOND_LIFE_ASSESSMENT",
) -> dict[str, Any]:
    """
    Calculate transparent, cross-checked economic estimates in INR for:
      1. Replacement (Brand New OEM pack + authorized labor)
      2. Repair & Module Refurbishment (Cell balancing, module replacement, BMS calibration)
      3. Second-Life Buyback / Residual Valuation (Sale for stationary solar storage)
      4. Strategic decision guidance & net financial impact
    """
    cap = float(capacity_kwh or 40.0)
    chem = str(chemistry or "LFP").upper()
    soh = float(max(0.0, min(100.0, soh_pct)))
    usable_kwh = round(cap * (soh / 100.0), 1)

    # 1. OEM Brand New Replacement Pack
    # Typical Indian market replacement costs: ₹12,000/kWh for LFP; ₹13,800/kWh for NMC
    rate_per_kwh = 12000.0 if "LFP" in chem else 13800.0
    pack_cells_cost = round((cap * rate_per_kwh) / 1000.0) * 1000.0
    oem_bms_unit = 24000.0
    oem_labor_and_pairing = 18000.0
    replacement_cost = round((pack_cells_cost + oem_bms_unit + oem_labor_and_pairing) / 1000.0) * 1000.0
    rep_min = round(replacement_cost * 0.94 / 1000.0) * 1000.0
    rep_max = round(replacement_cost * 1.06 / 1000.0) * 1000.0

    replacement_breakdown = [
        {
            "item": f"OEM Cell Modules & Housing ({cap:.1f} kWh {chem})",
            "cost_inr": pack_cells_cost,
            "note": f"Factory grade-A certified cell modules @ ₹{rate_per_kwh:,.0f}/kWh",
        },
        {
            "item": "Factory Smart BMS Unit & Wiring Harness",
            "cost_inr": oem_bms_unit,
            "note": "OEM master battery management controller with CANbus integration",
        },
        {
            "item": "Authorized High-Voltage Labor & Commissioning",
            "cost_inr": oem_labor_and_pairing,
            "note": "Pack de-mount, hoist installation, coolant loop vacuum fill & pairing",
        },
        {
            "item": "8-Year / 1,60,000 km Warranty Registration",
            "cost_inr": 0.0,
            "note": "Official manufacturer warranty certificate included",
        },
    ]

    # 2. Repair / Module Refurbishment
    # Calibrated against prevention.py (UNIT_COSTS_INR['repair_refurbishment'] = 42,000)
    # Cell balancing, replacing 1 degraded module string, thermal servicing & BMS flash
    diag_balancing = 8500.0
    cell_rebalance_cycle = 4500.0
    module_swap = round((16000.0 + (cap * 150.0)) / 500.0) * 500.0
    thermal_servicing = 6500.0
    bms_calibration_seal = 4500.0
    repair_cost = round((diag_balancing + cell_rebalance_cycle + module_swap + thermal_servicing + bms_calibration_seal) / 1000.0) * 1000.0
    repair_min = round(repair_cost * 0.90 / 1000.0) * 1000.0
    repair_max = round(repair_cost * 1.12 / 1000.0) * 1000.0

    repair_breakdown = [
        {
            "item": "High-Voltage Diagnostics & Voltage Imbalance Mapping",
            "cost_inr": diag_balancing,
            "note": "Automated individual cell internal resistance and delta-V scanning",
        },
        {
            "item": "Active Cell Re-balancing Cycle",
            "cost_inr": cell_rebalance_cycle,
            "note": "High-precision bench equalization across all series groups",
        },
        {
            "item": "Certified Replacement Module (1 Sub-pack)",
            "cost_inr": module_swap,
            "note": "Replaces the single degraded/weak cell cluster with matched cells",
        },
        {
            "item": "Thermal Interface & Manifold Servicing",
            "cost_inr": thermal_servicing,
            "note": "Replacement of silicone thermal pads, coolant purge & leak testing",
        },
        {
            "item": "BMS Recalibration & IP67 Enclosure Resealing",
            "cost_inr": bms_calibration_seal,
            "note": "Firmware SoC reset and hermetic chamber vacuum pressure seal test",
        },
    ]

    # 3. Second-Life Residual Valuation (Buyback value)
    # Stationary BESS buyers in India pay ~₹3,800 - ₹4,600 per usable kWh remaining
    buyback_rate_per_kwh = 4200.0
    second_life_value = round((usable_kwh * buyback_rate_per_kwh) / 1000.0) * 1000.0
    sl_min = round((usable_kwh * 3800.0) / 1000.0) * 1000.0
    sl_max = round((usable_kwh * 4600.0) / 1000.0) * 1000.0

    second_life_breakdown = [
        {
            "item": f"Usable Energy Retention Valuation ({usable_kwh:.1f} kWh @ ₹{buyback_rate_per_kwh:,.0f}/kWh)",
            "cost_inr": second_life_value,
            "note": "Certified stationary BESS & solar microgrid marketplace recovery",
        },
        {
            "item": "Free Hazardous Material Pickup & Transport",
            "cost_inr": 0.0,
            "note": "Compliant ADR/PESO logistics covered by circular buyer partner",
        },
        {
            "item": "Digital Battery Passport & De-registration Certificate",
            "cost_inr": 0.0,
            "note": "Official EV RTO de-registration record issued automatically",
        },
    ]

    # 4. Economic Comparison & Savings
    savings_repair_vs_replace = replacement_cost - repair_cost
    net_upgrade_with_buyback = replacement_cost - second_life_value

    is_second_life = pathway == "SECOND_LIFE_ASSESSMENT" or (55.0 <= soh < 75.0)
    is_repair = pathway == "REPAIR_REFURBISHMENT" or (70.0 <= soh < 80.0)

    if is_second_life:
        recommended_option = "second_life"
        headline = "Second-Life Monetization yields the highest circular return"
        summary = (
            f"At {soh:.1f}% health ({usable_kwh} kWh usable retention), your battery is below "
            f"the optimal highway traction floor. Rather than spending ₹{replacement_cost:,.0f} for "
            f"a full out-of-warranty replacement or ₹{repair_cost:,.0f} on temporary patching, "
            f"monetizing your pack in the circular marketplace returns ~₹{second_life_value:,.0f} in "
            f"cash or credit towards a new pack or residential solar storage."
        )
    elif is_repair:
        recommended_option = "repair"
        headline = "Module refurbishment is the most economical immediate step"
        summary = (
            f"At {soh:.1f}% health, localized cell balancing and module repair (₹{repair_cost:,.0f}) "
            f"saves ₹{savings_repair_vs_replace:,.0f} compared to a new pack, restoring reliable city range "
            f"for approximately 12–18 months."
        )
    elif soh >= 80.0:
        recommended_option = "continue_use"
        headline = "Battery is healthy — No capital replacement or repair needed"
        summary = (
            f"Operating at {soh:.1f}% health with {usable_kwh} kWh capacity. Continue scheduled routine "
            f"inspections and standard AC charging."
        )
    else:  # EOL Recycling
        recommended_option = "recycling"
        headline = "Certified circular recycling recovery recommended"
        summary = (
            f"Capacity ({soh:.1f}%) is exhausted for secondary energy storage. Directing to certified "
            f"hydrometallurgical recycling recovers raw materials value (~₹18,000–₹26,000 scrap credit) "
            f"with zero hazardous waste."
        )

    return {
        "capacity_kwh": cap,
        "usable_remaining_kwh": usable_kwh,
        "chemistry": chem,
        "soh_pct": soh,
        "replacement": {
            "title": "Brand New OEM Battery Pack",
            "estimated_cost_inr": replacement_cost,
            "cost_range_inr": [rep_min, rep_max],
            "rate_per_kwh_inr": rate_per_kwh,
            "warranty_years": 8,
            "expected_life_years": 8,
            "description": "Full factory replacement from authorized OEM service center.",
            "itemized_breakdown": replacement_breakdown,
            "pros": [
                "Restores 100% original driving range",
                "Comes with official 8-year / 1,60,000 km manufacturer warranty",
                "Factory calibrated BMS and fresh thermal management",
            ],
            "cons": [
                "Highest upfront capital outlay (~40-50% of original EV price)",
                "Longer service center downtime (7-14 days)",
            ],
        },
        "repair": {
            "title": "Module Refurbishment & Re-balancing",
            "estimated_cost_inr": repair_cost,
            "cost_range_inr": [repair_min, repair_max],
            "expected_life_extension_months": 18,
            "description": "Cell re-balancing, weak module replacement, thermal pad refresh, and BMS flash.",
            "itemized_breakdown": repair_breakdown,
            "pros": [
                f"Saves ~₹{savings_repair_vs_replace:,.0f} compared to full replacement",
                "Fast turnaround (3-5 business days)",
                "Addresses voltage spread and localized hot cells",
            ],
            "cons": [
                "Temporary extension (12–18 months of city use)",
                "Does not restore 100% highway range",
            ],
        },
        "second_life": {
            "title": "Second-Life Buyback & Monetization",
            "estimated_residual_value_inr": second_life_value,
            "value_range_inr": [sl_min, sl_max],
            "rate_per_kwh_inr": buyback_rate_per_kwh,
            "description": "Sell pack into the certified stationary energy storage / solar microgrid market.",
            "itemized_breakdown": second_life_breakdown,
            "pros": [
                f"Recovers ~₹{second_life_value:,.0f} cash or trade-in credit",
                "Zero landfill or environmental disposal fee",
                f"Net upgrade cost drops to ₹{net_upgrade_with_buyback:,.0f} if purchasing a new pack",
            ],
            "cons": [
                "Pack is retired from vehicle traction use",
            ],
        },
        "economic_verdict": {
            "recommended_option": recommended_option,
            "headline": headline,
            "summary": summary,
            "savings_vs_replacement_inr": savings_repair_vs_replace,
            "net_upgrade_with_buyback_inr": net_upgrade_with_buyback,
        },
    }

