def lookup_vehicle_spec(brand: str | None, model: str | None) -> dict[str, Any]:
    """Find nominal technical specs for an EV model or return safe defaults."""
    query = f"{brand or ''} {model or ''}".strip().lower()
    for key, spec in VEHICLE_SPECS.items():
        if key in query or (model and key in model.lower()):
            return spec.copy()
    # Brand-level fallbacks
    brand_lower = (brand or "").lower()
    if "tata" in brand_lower:
        return {"capacity_kwh": 35.0, "chemistry": "LFP", "epk": 0.135, "nominal_range_km": 280}
    if "mg" in brand_lower:
        return {"capacity_kwh": 45.0, "chemistry": "LFP", "epk": 0.150, "nominal_range_km": 320}
    if "mahindra" in brand_lower:
        return {"capacity_kwh": 39.4, "chemistry": "NMC", "epk": 0.155, "nominal_range_km": 300}
